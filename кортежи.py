# Рассмотрим другой случай, где "*" стоит и в переменной, а в функции print():
name, *marks, predlast, last = 'Ivan', 4, 5, 3, 5, 7
print(name)  # Получается Ivan.
print(*marks)  # Получаются просто значения 4, 5, 3.
print(predlast)  # Получается 5.
print(last)  # Получается 7.



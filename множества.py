# Для чего нужны множества?
# Мы их можем объединять, пересекать, удалять.

st1 = {1, 2, 33}  # сделали 1-ое множество
st2 = {1, 2, 44}  # сделали 2-ое множество

# Объединим эти два множества:

res = st1.union(st2)
print(res)  # результат: {1, 2, 33, 44}

# То же самое объединение можно написать по другому следующим образом:
res = st1 | st2
print(res)

# Поговорим о пересечении этих двух множеств: ПЕРЕСЕЧЕНИЕ НАМ ДАЕТ ВСЕ ЭЛЕМЕНТЫ, КОТОРЫЕ ОДИНАКОВЫЕ В ДВУХ РАЗНЫХ МНОЖЕСТВАХ.
res = st1.intersection(st2)  # Перечение - это общие, что есть и 1-ом и во 2-ом множестве. Т.е. одинаковые объекты.
print(res)  # результат: {1, 2}
# То же самое пересечение можно написать по другому следующим образом:
res = st1 & st2
print(res)

# Вычитание множеств:

res = st1.difference(st2)  # Вычитание множеств можно делать через данный метод.
res = st1 - st2  # Или вычитать одно значение из другого. Этим хотим узнать, что ушло из st1.
print(res)  # результат: {33}.Так как пересечения сразу уйдут и останется только 33

res = st2 - st1
print(res)  # результат: {44}

# Один из самых важных элементов - это симмметрическая разность.
res = st1.symmetric_difference(st2)  # Симметрическая разность показывает все элементы, которые различаются в двух разных множествах.
res = st1 ^ st2  # то же самое, что и в строчке 230
print(res)  # результат: {33, 44}

#  ВО МНОЖЕСТВАХ ЕСТЬ ПОНЯТИЕ super МНОЖЕСТВА И подмножества

st1 = {1, 2, 33}
st2 = {1, 2, 44}
st3 = {1, 2}  # Получается, что 1 и 2 входит и в множество st1  и во множество st2.
# Таким образом: {1, 2} является ПОДМНОЖЕСТВОМ и множества st2 и множества st1.
# А множества st2 и st1 по отношению к множеству st3 являются SUPER множествами.

print(st3.issubset(st1))  # Множество st3 является ли оно подмножеством st1?
# результат: True
print(st1.issuperset(st3))  # Множество st1 является ли по отношению к st3 SUPER множеством?
# результат: True

















# Как происходит добавление не одного элемента, а сразу несколько элементов во множество? Ответ: с помощью метода update().
st.update()  # в эти скобки мы можем положить список, кортеж, множество. Т.е. какую-либо коллекцию из набора элементов.
st.update('old')  # Если положим переменную, то она зайдет, как объект. Результат: {33, 'l', 100, 44, 22, 'd', 'o'}
# Пропишем эту переменную в виде множества:

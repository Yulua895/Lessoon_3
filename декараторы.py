def in_out(func):
    def wrapper(*args, **kwargs):
        print(f'Функция {func.__name__} приняла {args}, {kwargs} ')
        res = func(*args, **kwargs)
        print(f'Функция {func.__name__} вернула {res} ')
        return res
    return wrapper


# 1-ый полезный декоратор - это декоратор, который позволит нам замерить время выполнения программы.
def time_run(func):  # декоратор для измерения времени выполнения
    def wrapper(*args, **kwargs):
        start = time.time() # здесь зафиксируем время старта.
        # Функция time.time() она вызовет время с 1 января 1970 года. Количество секунд с момента введения системы в эксплотацию.
        func(*args, **kwargs)  # здесь мы выполняем саму функцию
        end = time.time()
        duration = end - start
        print(f'Функция {func.__name__} выполнения {duration:.2f} секунд')  # ввели ограничения после запятой оставляем два знака ({duration:.2f})
    return wrapper





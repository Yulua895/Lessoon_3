# И если что-то происходит, а именно появляется нулевой остаток при делении, то мы говорим,что это число составное.

# Цикл for - это цикл по количеству объектов, а цикл while - это цикл по условию.
# Цикл for четко понимает сколько он будет делать итераций, то цикл while этого изначально не знает.

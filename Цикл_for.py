# Цикл for перебирает все то, что стоит после ключевого слова in.
# Если после in стоит range то это будет генератор числовой последовательности.
# Если это будет строка, то он будет перебирать каждый символ.
# Если стоит список, то будет перебирать объекты из списка.
# Если будет кортеж, то будет перебирать объекты кортежа.

# Цикл for применяется, если есть какие-либо коллекции и их надо перебрать.
